import os
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Generator

import psycopg
from dotenv import load_dotenv
from psycopg.rows import dict_row

PROJECT_ROOT = Path(__file__).resolve().parents[2]
load_dotenv(PROJECT_ROOT / ".env")

SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS expenses (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        amount NUMERIC NOT NULL CHECK (amount > 0),
        category TEXT NOT NULL,
        expense_date DATE NOT NULL,
        notes TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS recurring_income (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        person TEXT NOT NULL,
        source TEXT NOT NULL,
        amount NUMERIC NOT NULL CHECK (amount > 0),
        frequency TEXT NOT NULL CHECK (frequency IN ('monthly', 'biweekly', 'once')),
        income_date DATE,
        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CHECK (
            (frequency = 'once' AND income_date IS NOT NULL)
            OR (frequency IN ('monthly', 'biweekly') AND income_date IS NULL)
        )
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS recurring_bills (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        amount NUMERIC NOT NULL CHECK (amount > 0),
        category TEXT NOT NULL DEFAULT 'Bills',
        due_day INTEGER NOT NULL CHECK (due_day BETWEEN 1 AND 31),
        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS bill_payments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        bill_id INTEGER NOT NULL
            REFERENCES recurring_bills(id) ON DELETE CASCADE,
        period TEXT NOT NULL,
        amount NUMERIC NOT NULL CHECK (amount > 0),
        expense_id INTEGER NOT NULL UNIQUE
            REFERENCES expenses(id) ON DELETE CASCADE,
        paid_on DATE NOT NULL,
        UNIQUE (bill_id, period)
    )
    """,
)


@contextmanager
def get_connection() -> Generator[psycopg.Connection[dict[str, Any]], None, None]:
    """Yield a short-lived pooled connection for application queries."""
    database_url = _get_database_url("DATABASE_URL")
    with _connect(database_url) as connection:
        yield connection


@contextmanager
def get_migration_connection() -> Generator[
    psycopg.Connection[dict[str, Any]], None, None
]:
    """Yield a direct connection for schema changes and data migration."""
    database_url = _get_database_url("DATABASE_URL_UNPOOLED")
    with _connect(database_url) as connection:
        yield connection


def _get_database_url(variable: str) -> str:
    database_url = os.environ.get(variable)
    if not database_url:
        raise RuntimeError(
            f"{variable} is not set. Configure it in the project-root .env file "
            "or in the hosting environment."
        )
    return database_url


@contextmanager
def _connect(
    database_url: str,
) -> Generator[psycopg.Connection[dict[str, Any]], None, None]:
    with psycopg.connect(
        database_url,
        sslmode="require",
        connect_timeout=10,
        row_factory=dict_row,
    ) as connection:
        yield connection


def initialize_database() -> None:
    """Create the PostgreSQL tables if they do not already exist."""
    with get_migration_connection() as connection:
        for statement in SCHEMA_STATEMENTS:
            connection.execute(statement)


if __name__ == "__main__":
    initialize_database()
    print("PostgreSQL schema initialized.")
